export const media = {
  ...coreMedia,
  ...lodgeMedia,
} satisfies Record<string, MediaAsset>;

export type MediaId = keyof typeof media;

export function getMedia(id: MediaId | string): MediaAsset {
  if (id in media) {
    return media[id as MediaId];
  }
  return {
    id,
    kind: "image",
    src: "",
    alt: "Media to be supplied",
    status: "missing",
  };
}

export function mediaSrc(id: MediaId | string, fallback = "/images/official/tanzania.jpg") {
  const item = getMedia(id);
  return item.src || fallback;
}
